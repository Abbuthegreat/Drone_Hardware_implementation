#!/usr/bin/env python3
"""
record.py - record Intel RealSense (D435i / D455) RGB + depth (aligned to color) for
offline ORB-SLAM3 + human detection.

Start it BEFORE takeoff with the drone sitting still (it measures gravity for 1 s so the
map knows which way is "up"). Stop it after landing with Ctrl+C (or `pkill -INT -f record.py`).

    python3 record.py                      # 640x480 @ 30 fps into ~/flights/<date_time>/
    python3 record.py --preview            # with a live preview window (needs a monitor)
    python3 record.py --duration 300       # auto-stop after 5 minutes
    python3 record.py --repair ~/flights/2026-09-30_22-10-00   # rebuild index after power loss

Output folder:
    rgb/000000.jpg ...      color frames (BGR JPEG)
    depth/000000.png ...    16-bit depth aligned to color (raw units, see meta.json)
    frames.csv              idx,t  (written live - survives power loss)
    associations.txt        TUM-style list used by ORB-SLAM3
    orbslam.yaml            ORB-SLAM3 settings with THIS camera's real intrinsics
    meta.json               intrinsics, depth scale, gravity vector, device info
"""
import argparse
import json
import os
import queue
import shutil
import signal
import sys
import threading
import time
from datetime import datetime

import numpy as np
import cv2

STOP = threading.Event()


def on_signal(signum, frame):
    print(f"\n[record] signal {signum} received - stopping...", flush=True)
    STOP.set()


# ----------------------------------------------------------------------------- helpers
def write_associations(run_dir):
    """(Re)build rgb.txt / depth.txt / associations.txt from frames.csv + files on disk."""
    csv_path = os.path.join(run_dir, "frames.csv")
    rows = []
    with open(csv_path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("idx"):
                continue
            idx, t = line.split(",")[:2]
            idx = int(idx)
            rgb = f"rgb/{idx:06d}.jpg"
            dep = f"depth/{idx:06d}.png"
            if os.path.exists(os.path.join(run_dir, rgb)) and os.path.exists(os.path.join(run_dir, dep)):
                rows.append((idx, float(t), rgb, dep))
    rows.sort()
    # after a power cut the last frames may be half-written -> keep only decodable ones at the tail
    good = []
    for k, r in enumerate(rows):
        if k >= len(rows) - 300:
            if cv2.imread(os.path.join(run_dir, r[2])) is None or \
               cv2.imread(os.path.join(run_dir, r[3]), cv2.IMREAD_UNCHANGED) is None:
                continue
        good.append(r)
    rows = good
    with open(os.path.join(run_dir, "associations.txt"), "w") as fa, \
         open(os.path.join(run_dir, "rgb.txt"), "w") as fr, \
         open(os.path.join(run_dir, "depth.txt"), "w") as fd:
        for idx, t, rgb, dep in rows:
            fa.write(f"{t:.6f} {rgb} {t:.6f} {dep}\n")
            fr.write(f"{t:.6f} {rgb}\n")
            fd.write(f"{t:.6f} {dep}\n")
    return len(rows)


def write_orbslam_yaml(path, intr, depth_scale, fps, baseline, n_features):
    k = intr.get("coeffs", [0, 0, 0, 0, 0])
    # RealSense color is usually "inverse brown conrady" with ~zero coeffs; only use
    # coefficients when the model is plain brown_conrady (OpenCV compatible).
    if "inverse" in intr.get("model", "").lower() or len(k) < 5:
        k = [0.0] * 5
    txt = f"""%YAML:1.0
# Auto-generated by record.py from the camera's factory calibration
File.version: "1.0"
Camera.type: "PinHole"
Camera1.fx: {intr['fx']:.6f}
Camera1.fy: {intr['fy']:.6f}
Camera1.cx: {intr['ppx']:.6f}
Camera1.cy: {intr['ppy']:.6f}
Camera1.k1: {k[0]:.8f}
Camera1.k2: {k[1]:.8f}
Camera1.p1: {k[2]:.8f}
Camera1.p2: {k[3]:.8f}
Camera1.k3: {k[4]:.8f}
Camera.width: {intr['width']}
Camera.height: {intr['height']}
Camera.fps: {fps}
# images are loaded with cv::imread -> BGR
Camera.RGB: 0
Stereo.ThDepth: 40.0
Stereo.b: {baseline:.4f}
RGBD.DepthMapFactor: {1.0 / depth_scale:.3f}
ORBextractor.nFeatures: {n_features}
ORBextractor.scaleFactor: 1.2
ORBextractor.nLevels: 8
ORBextractor.iniThFAST: 20
ORBextractor.minThFAST: 7
Viewer.KeyFrameSize: 0.05
Viewer.KeyFrameLineWidth: 1.0
Viewer.GraphLineWidth: 0.9
Viewer.PointSize: 2.0
Viewer.CameraSize: 0.08
Viewer.CameraLineWidth: 3.0
Viewer.ViewpointX: 0.0
Viewer.ViewpointY: -0.7
Viewer.ViewpointZ: -1.8
Viewer.ViewpointF: 500.0
"""
    with open(path, "w") as f:
        f.write(txt)


def measure_gravity(rs, serial, seconds=1.0):
    """Mean accelerometer vector (points UP, in IMU frame) with the drone at rest."""
    pipe = rs.pipeline()
    cfg = rs.config()
    cfg.enable_device(serial)
    cfg.enable_stream(rs.stream.accel)
    prof = pipe.start(cfg)
    samples = []
    t_end = time.time() + seconds + 0.5
    try:
        while time.time() < t_end:
            fs = pipe.wait_for_frames(2000)
            for fr in fs:
                if fr.is_motion_frame():
                    d = fr.as_motion_frame().get_motion_data()
                    samples.append((d.x, d.y, d.z))
    finally:
        pipe.stop()
    accel_profile = prof.get_stream(rs.stream.accel)
    if len(samples) < 10:
        return None, None
    s = np.array(samples[len(samples) // 3:])      # drop first samples
    return s.mean(axis=0), accel_profile


# ----------------------------------------------------------------------------- writer
def writer_worker(q, run_dir, jpeg_q, stats):
    jpg_params = [cv2.IMWRITE_JPEG_QUALITY, jpeg_q]
    png_params = [cv2.IMWRITE_PNG_COMPRESSION, 1]
    while True:
        item = q.get()
        if item is None:
            q.task_done()
            break
        idx, color, depth = item
        try:
            # write depth first; the jpg existing implies the pair is complete enough
            cv2.imwrite(os.path.join(run_dir, "depth", f"{idx:06d}.png"), depth, png_params)
            cv2.imwrite(os.path.join(run_dir, "rgb", f"{idx:06d}.jpg"), color, jpg_params)
            stats["written"] += 1
        except Exception as e:  # disk full etc.
            print(f"[record] write error: {e}", flush=True)
            stats["write_errors"] += 1
        q.task_done()


# ----------------------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.expanduser("~/flights"))
    ap.add_argument("--width", type=int, default=640)
    ap.add_argument("--height", type=int, default=480)
    ap.add_argument("--fps", type=int, default=30)
    ap.add_argument("--duration", type=float, default=0, help="seconds, 0 = until Ctrl+C")
    ap.add_argument("--jpeg-quality", type=int, default=92)
    ap.add_argument("--writers", type=int, default=3)
    ap.add_argument("--preview", action="store_true")
    ap.add_argument("--no-imu", action="store_true", help="skip gravity measurement")
    ap.add_argument("--min-free-gb", type=float, default=1.0)
    ap.add_argument("--features", type=int, default=1250, help="ORB features in generated yaml")
    ap.add_argument("--repair", metavar="RUN_DIR", help="rebuild associations.txt for a run and exit")
    args = ap.parse_args()

    if args.repair:
        n = write_associations(args.repair)
        print(f"[record] rebuilt associations.txt with {n} frames")
        return

    import pyrealsense2 as rs

    signal.signal(signal.SIGINT, on_signal)
    signal.signal(signal.SIGTERM, on_signal)

    ctx = rs.context()
    devs = ctx.query_devices()
    if len(devs) == 0:
        sys.exit("[record] No RealSense camera found. Check USB (must be USB 3).")
    dev = devs[0]
    name = dev.get_info(rs.camera_info.name)
    serial = dev.get_info(rs.camera_info.serial_number)
    usb = dev.get_info(rs.camera_info.usb_type_descriptor) if dev.supports(rs.camera_info.usb_type_descriptor) else "?"
    print(f"[record] Camera: {name}  serial {serial}  USB {usb}")
    if usb.startswith("2"):
        print("[record] WARNING: camera is on USB 2 - use a USB 3 port/cable or frames will drop!")

    run_dir = os.path.join(args.out, datetime.now().strftime("%Y-%m-%d_%H-%M-%S"))
    os.makedirs(os.path.join(run_dir, "rgb"), exist_ok=True)
    os.makedirs(os.path.join(run_dir, "depth"), exist_ok=True)
    print(f"[record] Saving to {run_dir}")

    # ---- gravity (drone must be still) ----
    gravity_imu, accel_profile = None, None
    if not args.no_imu:
        try:
            print("[record] Measuring gravity - keep the drone still...")
            gravity_imu, accel_profile = measure_gravity(rs, serial)
            print(f"[record] accel mean = {gravity_imu}")
        except Exception as e:
            print(f"[record] IMU not available ({e}) - continuing without gravity")

    # ---- video pipeline ----
    pipe = rs.pipeline()
    cfg = rs.config()
    cfg.enable_device(serial)
    cfg.enable_stream(rs.stream.depth, args.width, args.height, rs.format.z16, args.fps)
    cfg.enable_stream(rs.stream.color, args.width, args.height, rs.format.bgr8, args.fps)
    profile = pipe.start(cfg)
    depth_sensor = profile.get_device().first_depth_sensor()
    depth_scale = depth_sensor.get_depth_scale()
    try:
        depth_sensor.set_option(rs.option.emitter_enabled, 1)
    except Exception:
        pass
    # keep constant frame rate even in low light (less blur-induced frame drops)
    try:
        for s in profile.get_device().query_sensors():
            if s.supports(rs.option.auto_exposure_priority):
                s.set_option(rs.option.auto_exposure_priority, 0)
    except Exception:
        pass

    color_profile = profile.get_stream(rs.stream.color).as_video_stream_profile()
    ci = color_profile.get_intrinsics()
    intr = dict(width=ci.width, height=ci.height, fx=ci.fx, fy=ci.fy, ppx=ci.ppx, ppy=ci.ppy,
                model=str(ci.model), coeffs=list(ci.coeffs))

    # gravity "up" direction in the COLOR camera frame
    up_cam = None
    if gravity_imu is not None:
        g = np.array(gravity_imu, dtype=float)
        try:
            ext = accel_profile.get_extrinsics_to(color_profile)
            R = np.array(ext.rotation, dtype=float).reshape(3, 3).T  # librealsense is column-major
            g = R @ g
        except Exception as e:
            print(f"[record] accel->color extrinsics unavailable ({e}), assuming aligned axes")
        up_cam = (g / np.linalg.norm(g)).tolist()
        print(f"[record] 'up' in camera frame = {np.round(up_cam, 3)}")

    baseline = 0.095 if "D455" in name or "D456" in name else 0.050
    write_orbslam_yaml(os.path.join(run_dir, "orbslam.yaml"), intr, depth_scale, args.fps, baseline, args.features)

    meta = dict(device=name, serial=serial, usb=usb, width=args.width, height=args.height, fps=args.fps,
                depth_scale=depth_scale, color_intrinsics=intr, up_camera_frame=up_cam,
                gravity_raw=None if gravity_imu is None else list(map(float, gravity_imu)),
                start_time=datetime.now().isoformat(), baseline=baseline)
    with open(os.path.join(run_dir, "meta.json"), "w") as f:
        json.dump(meta, f, indent=2)

    align = rs.align(rs.stream.color)

    # warm-up (auto exposure settles)
    for _ in range(15):
        pipe.wait_for_frames(5000)

    q = queue.Queue(maxsize=150)
    stats = dict(written=0, write_errors=0)
    workers = [threading.Thread(target=writer_worker, args=(q, run_dir, args.jpeg_quality, stats), daemon=True)
               for _ in range(args.writers)]
    for w in workers:
        w.start()

    fcsv = open(os.path.join(run_dir, "frames.csv"), "w")
    fcsv.write("idx,t,t_color_ms,t_depth_ms\n")

    def syncer():  # power can be cut at any time -> push data to disk every 2 s
        while not STOP.is_set():
            time.sleep(2.0)
            try:
                fcsv.flush()
                os.fsync(fcsv.fileno())
                os.sync()
            except Exception:
                pass
    threading.Thread(target=syncer, daemon=True).start()

    idx, dropped = 0, 0
    t0_ms, last_ts = None, None
    t_start = time.time()
    t_report = t_start
    n_since = 0
    show = args.preview and os.environ.get("DISPLAY")
    print("[record] RECORDING. Ctrl+C to stop.", flush=True)

    try:
        while not STOP.is_set():
            try:
                frames = pipe.wait_for_frames(3000)
            except RuntimeError as e:
                print(f"[record] frame timeout: {e}", flush=True)
                continue
            frames = align.process(frames)
            cf = frames.get_color_frame()
            df = frames.get_depth_frame()
            if not cf or not df:
                continue
            ts = frames.get_timestamp()
            if last_ts is not None and ts <= last_ts:
                continue
            last_ts = ts
            if t0_ms is None:
                t0_ms = ts
            t = (ts - t0_ms) / 1000.0

            color = np.asanyarray(cf.get_data()).copy()
            depth = np.asanyarray(df.get_data()).copy()
            try:
                q.put_nowait((idx, color, depth))
                fcsv.write(f"{idx},{t:.6f},{cf.get_timestamp():.3f},{df.get_timestamp():.3f}\n")
                idx += 1
            except queue.Full:
                dropped += 1
            n_since += 1

            if show and idx % 2 == 0:
                dvis = cv2.applyColorMap(cv2.convertScaleAbs(depth, alpha=255.0 / (6.0 / depth_scale)), cv2.COLORMAP_JET)
                cv2.imshow("record (q = stop)", np.hstack([color, dvis]))
                if cv2.waitKey(1) & 0xFF == ord("q"):
                    STOP.set()

            now = time.time()
            if now - t_report >= 5.0:
                fcsv.flush()
                free_gb = shutil.disk_usage(run_dir).free / 1e9
                print(f"[record] t={t:7.1f}s frames={idx} fps={n_since / (now - t_report):5.1f} "
                      f"queue={q.qsize()} dropped={dropped} free={free_gb:.1f}GB", flush=True)
                t_report, n_since = now, 0
                if free_gb < args.min_free_gb:
                    print("[record] Disk almost full - stopping.")
                    STOP.set()
            if args.duration and now - t_start >= args.duration:
                STOP.set()
    finally:
        print("[record] Stopping camera, flushing files...", flush=True)
        try:
            pipe.stop()
        except Exception:
            pass
        for _ in workers:
            q.put(None)
        for w in workers:
            w.join(timeout=60)
        fcsv.close()
        n = write_associations(run_dir)
        # rename folder to START_to_STOP so the name shows the full recording time
        try:
            new_dir = run_dir + "_to_" + datetime.now().strftime("%H-%M-%S")
            os.rename(run_dir, new_dir)
            run_dir = new_dir
        except Exception as e:
            print(f"[record] could not rename folder: {e}")
        dur = time.time() - t_start
        print(f"[record] Done: {n} frames in {dur:.0f}s ({n / max(dur, 1e-3):.1f} fps), dropped {dropped}")
        print(f"[record] Run folder: {run_dir}")
        if show:
            cv2.destroyAllWindows()


if __name__ == "__main__":
    main()
